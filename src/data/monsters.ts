/** Fungsi helper untuk mengambil monster berdasarkan level */
export function getMonsterForLevel(levelNum: number): GeometryMonster {
  if (MONSTERS_DATABASE[levelNum]) {
    return MONSTERS_DATABASE[levelNum];
  }
  // Fallback generik jika level lebih tinggi
  return {
    id: `mob-generic-${levelNum}`,
    levelNum,
    name: `Monster Penjelajah Lv.${levelNum}`,
    title: 'Penantang Geometri Misterius',
    shapeType: 'polygon',
    maxHp: 80 + levelNum * 20,
    atk: 10 + levelNum * 3,
    def: 5 + levelNum * 2,
    color: '#8b5cf6',
    gradient: 'linear-gradient(135deg, #a78bfa 0%, #6d28d9 100%)',
    description: 'Monster geometri liar yang menjaga jalur rahasia pulau.',
    skill: {
      name: 'Serangan Garis Geometri',
      description: 'Melancarkan serangan garis lurus bertekanan tinggi.',
      damage: 15 + levelNum * 2,
    },
    dropReward: {
      exp: 30 + levelNum * 10,
      coins: 10 + levelNum * 5,
      stars: 3,
      diamonds: 2,
    },
  };
}
